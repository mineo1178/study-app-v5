import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { join } from "node:path";
import { createServer } from "vite";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || join(homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright"));
const server = await createServer({ server: { host: "127.0.0.1", port: 5189, strictPort: true }, logLevel: "error" });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true, channel: "msedge" });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  await context.route("**/*", r => new URL(r.request().url()).hostname === "127.0.0.1" ? r.continue() : r.abort());
  const page = await context.newPage(), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.clock.install({ time: new Date("2026-11-11T12:00:00+09:00") });
  await page.goto("http://127.0.0.1:5189/tests/timer-review-browser.html");
  const keys = { data: "study-review-v1:sample:fixture:fixture:sample:sample-data", draft: "study-review-v1:sample:fixture:fixture:sample:draft", plan: "study-review-v1:sample:fixture:fixture:sample:target-plan" };
  // Reuse fictional fixtures only. Nine IDs exercise rotation independently of real data.
  await page.evaluate(async keys => {
    const { sampleQuestions, nextProgress } = await import("/src/review/model.ts");
    const questions = Array.from({ length: 9 }, (_, i) => ({ ...sampleQuestions[i % sampleQuestions.length], id: `fixture-${i}`, unit: `fixture-${i}` }));
    const progress = questions.slice(0, 7).map(q => nextProgress(undefined, { id: `old-${q.id}`, questionId: q.id, questionVersion: q.version, correct: false, answeredAt: Date.now() - 86400000, mode: "daily" }));
    localStorage.setItem(keys.data, JSON.stringify({ questions, progress, history: [], weaknesses: [] }));
  }, keys);
  await page.reload();
  const panel = page.getByRole("region", { name: "テスト対策・復習", exact: true });
  const start = () => panel.getByRole("button", { name: /^今日の\d問を始める$/ });
  await start().waitFor();
  const shown = () => panel.locator("p.bg-blue-50").allTextContents();
  const units = texts => texts.map(t => /fixture-\d/.exec(t)?.[0]);
  const displayed = units(await shown());
  assert.equal(displayed.length, 5);
  await page.reload(); await start().waitFor(); assert.deepEqual(units(await shown()), displayed);
  await panel.getByRole("button", { name: "間違い直しを始める", exact: true }).click();
  const readDraft = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), keys.draft);
  let draft = await readDraft();
  assert.deepEqual(draft.questions.map(q => q.unit), displayed, "wrong-only start must keep the displayed selection, not rotate the smaller wrong-only pool again");
  await panel.getByRole("button", { name: /^1\. / }).click();
  await panel.getByRole("button", { name: "回答を決めて次へ", exact: true }).click();
  draft = await readDraft();
  await page.clock.setSystemTime(new Date("2026-11-12T12:00:00+09:00")); await page.reload();
  assert.deepEqual(await readDraft(), draft, "next-day reload must keep started questions and answers");
  assert.match(await panel.getByRole("status").innerText(), /開始日：2026-11-11/);
  await page.evaluate(key => localStorage.removeItem(key), keys.draft); await page.reload(); await start().waitFor();
  const nextDay = units(await shown()); assert.notDeepEqual(nextDay, displayed);
  await start().click(); assert.deepEqual((await readDraft()).questions.map(q => q.unit), nextDay);
  await page.evaluate(key => localStorage.removeItem(key), keys.draft); await page.reload(); await start().waitFor();
  await page.clock.setSystemTime(new Date("2026-11-13T12:00:00+09:00"));
  await start().click(); assert.equal(await readDraft(), null, "stale-day click refreshes preview before creating a draft");
  const refreshed = units(await shown());
  await start().click(); assert.deepEqual((await readDraft()).questions.map(q => q.unit), refreshed);
  // Change a plan through the real import UI; start must use the new preview.
  await page.evaluate(key => localStorage.removeItem(key), keys.draft); await page.reload(); await start().waitFor();
  const data = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), keys.data);
  const plan = { schemaVersion: 1, label: "Fixture exam", testDay: "2026-11-15", items: data.questions.slice(7).map(q => ({ questionId: q.id, questionVersion: q.version, priority: 1, reason: "fixture reason", evidence: "fictional", scopeBasis: "fictional" })), gaps: [], notes: [] };
  await panel.getByText("この端末のテスト対策計画", { exact: true }).click();
  const upload = async value => {
    await panel.getByLabel("根拠付き対策計画", { exact: true }).setInputFiles({ name: "fixture.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(value)) });
    await panel.getByText("計画を確認中…", { exact: true }).waitFor({ state: "hidden" });
  };
  await upload(plan); await panel.getByText("対策計画：設定済み ／ 今日の候補：2問", { exact: true }).waitFor();
  const planned = units(await shown()); assert.equal(planned.length, 2);
  await start().click(); assert.deepEqual((await readDraft()).questions.map(q => q.unit), planned);
  await page.evaluate(key => localStorage.removeItem(key), keys.draft); await page.reload(); await start().waitFor();
  await panel.getByText("この端末のテスト対策計画", { exact: true }).click();
  await upload({ ...plan, items: [{ ...plan.items[0], questionVersion: "missing-version" }] });
  await panel.getByText("対策計画：設定済み ／ 今日の候補：0問", { exact: true }).waitFor();
  assert.equal(await start().isDisabled(), true);
  await upload({ ...plan, testDay: "2026-11-14" });
  await panel.getByText(/対策計画：日程不一致/).waitFor(); assert.equal((await shown()).length, 5);
  await panel.getByLabel("出題診断").getByText("出題診断（この端末の読込時点）", { exact: true }).click();
  assert.match(await panel.getByLabel("出題診断").innerText(), /公開問題の未出題：2問 ／ 出題済み：7問/);
  console.log("PASS review: preview/start, wrong-only subset, same-day stability, next-day rotation, answered draft restore, immediate plan import, version shortage, schedule mismatch, diagnostics");

  // Freeze monotonic time while wall time advances: simulate an OS sleep.
  await page.clock.pauseAt(new Date("2026-11-13T13:00:00+09:00"));
  await page.getByRole("button", { name: "Calculation fixture", exact: true }).click();
  const timer = page.locator("p[aria-live=off]");
  await page.getByRole("button", { name: "計算をはじめる", exact: true }).click();
  await page.clock.runFor(2000); assert.equal(await timer.innerText(), "0:02");
  const wall = await page.evaluate(() => Date.now());
  await page.clock.setSystemTime(wall + 600000);
  await page.evaluate(() => window.dispatchEvent(new Event("pageshow")));
  assert.equal(await timer.innerText(), "10:02");
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  assert.equal(await timer.innerText(), "10:02", "repeated recovery must not double count");
  await page.clock.setSystemTime(wall - 60000);
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  assert.equal(await timer.innerText(), "10:02", "backward clock must not decrease recorded time");
  await page.reload(); await page.getByRole("button", { name: "Calculation fixture", exact: true }).click();
  assert.equal(await timer.innerText(), "10:02");
  await page.clock.runFor(10000); assert.equal(await timer.innerText(), "10:02", "reload restores paused, without counting a closed page");
  await page.getByRole("button", { name: "計測を再開", exact: true }).click(); await page.clock.runFor(3000);
  await page.getByRole("button", { name: "計算を終了して結果を記録", exact: true }).click();
  assert.equal(await timer.innerText(), "10:05");
  await page.getByRole("button", { name: "この結果を保存", exact: true }).click();
  await page.getByRole("alert").getByText(/保存できなかったよ/).waitFor();
  assert.equal(await timer.innerText(), "10:05");
  console.log("PASS calculation: normal, sleeping wall clock, pageshow/focus, repeated recovery, backward clock, reload pause/resume, manual stop, failed save preserves draft");

  // pagehide may precede document.hidden. It must not immediately clear hiddenSince.
  await page.reload();
  const state = async () => JSON.parse(await page.getByLabel("study state").innerText());
  const initial = await state();
  await page.evaluate(() => window.dispatchEvent(new Event("pagehide")));
  assert.equal((await state()).hiddenSince, initial.sessionStartTime);
  await page.clock.setSystemTime(initial.sessionStartTime + 299999);
  await page.evaluate(() => window.dispatchEvent(new Event("pageshow")));
  assert.equal((await state()).backgroundReviewRequired, false);
  await page.evaluate(() => window.dispatchEvent(new Event("pagehide")));
  await page.clock.setSystemTime(initial.sessionStartTime + 599999);
  await page.evaluate(() => window.dispatchEvent(new Event("pageshow")));
  assert.equal((await state()).backgroundReviewRequired, true); assert.equal((await state()).isRunning, true);
  await page.clock.setSystemTime(initial.sessionStartTime + 899999);
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  assert.equal((await state()).isRunning, true);
  await page.clock.setSystemTime(initial.sessionStartTime + 900000);
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  const stopped = await state(); assert.equal(stopped.isRunning, false);
  assert.equal(stopped.history.length, 1); assert.equal(stopped.history[0].duration, 900);
  assert.equal(stopped.history[0].reviewStatus, "pending"); assert.equal(stopped.history[0].creditedDuration, 0);
  await page.evaluate(() => { window.dispatchEvent(new Event("pageshow")); window.dispatchEvent(new Event("focus")); });
  assert.deepEqual((await state()).history, stopped.history);
  console.log("PASS study: pagehide ordering, 4:59/5:00 background, 14:59/15:00 idle, pending/no automatic credit, repeated resume no duplicate save");
  assert.deepEqual(errors, []);
} finally { await browser?.close(); await server.close(); }
